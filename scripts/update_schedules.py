#!/usr/bin/env python3
"""Regenerate data/schedules.js from Metra's published weekday PDF schedules.

Usage (from the repo root):
    python3 -m venv .venv && .venv/bin/pip install -r scripts/requirements.txt
    .venv/bin/python scripts/update_schedules.py            # download + rewrite
    .venv/bin/python scripts/update_schedules.py --dry-run  # just print trains

Only data/schedules.js is rewritten; drive/walk settings in data/config.js are left alone.
"""
import argparse
import datetime
import re
import sys
import tempfile
import urllib.request
from pathlib import Path

from pypdf import PdfReader

PDF_URL = "https://schedules.metrarail.com/pdf/{}.pdf"
OUT = Path(__file__).resolve().parent.parent / "data" / "schedules.js"

# key in config.js -> (PDF name, home station, downtown terminal), as named in the PDF
LINES = {
    "NCS": ("NCS", "Mundelein", "Union Station"),
    "MDN": ("MD-N", "Prairie Crossing", "Union Station"),
    "UPNW": ("UP-NW", "Barrington", "Ogilvie (OTC)"),
}

TIME = re.compile(r"\b(\d{1,2}):(\d{2})\b")
TRAIN = re.compile(r"\b\d{2,5}\b")


def download(pdf_name, dest_dir):
    path = Path(dest_dir) / f"{pdf_name}.pdf"
    req = urllib.request.Request(PDF_URL.format(pdf_name), headers={"User-Agent": "commute-planner"})
    with urllib.request.urlopen(req, timeout=60) as resp:
        path.write_bytes(resp.read())
    return path


def parse_pdf(path):
    """Return {"inbound": [...], "outbound": [...]}, each train as {train, stops: {station: minutes}}.

    Each weekday table page has a header row of train numbers, an AM/PM row, then one row per
    station. Times are matched to trains by horizontal position because express trains leave
    blank cells. Within a train, times only move forward, which resolves AM/PM and midnight.
    """
    out = {"inbound": [], "outbound": []}
    for page in PdfReader(path).pages:
        lines = (page.extract_text(extraction_mode="layout") or "").split("\n")
        title = next((l for l in lines if re.search(r"Weekday (Inbound|Outbound)", l)), None)
        if not title:
            continue
        direction = "inbound" if "Inbound" in title else "outbound"
        hi = next(i for i, l in enumerate(lines) if "Zone" in l)
        header = lines[hi]
        label_start = header.index(" to ") + 4
        label_end = label_start + re.search(r"\S+(\s\S+)*", header[label_start:]).end()
        cols = [(m.group(), (m.start() + m.end()) / 2) for m in TRAIN.finditer(header, label_end)]
        if not cols:
            raise ValueError(f"{path.name}: no train numbers found in header: {header.strip()!r}")

        def col_of(pos):
            return min(range(len(cols)), key=lambda c: abs(cols[c][1] - pos))

        ampm = {col_of((m.start() + m.end()) / 2): m.group()
                for m in re.finditer(r"\b(AM|PM)\b", lines[hi + 1])}
        cells = [[] for _ in cols]
        for line in lines[hi + 2:]:
            times = list(TIME.finditer(line))
            if not times:
                continue
            name = re.sub(r"^[\s●]*\d\s+", "", line[:times[0].start()])
            name = re.sub(r"\s+", " ", name).strip()
            for m in times:
                minutes12 = int(m.group(1)) % 12 * 60 + int(m.group(2))
                cells[col_of((m.start() + m.end()) / 2)].append((name, minutes12))

        for c, (train, _) in enumerate(cols):
            stops, prev = {}, None
            for name, m12 in cells[c]:
                if prev is None:
                    v = m12 + (720 if ampm.get(c) == "PM" else 0)
                else:
                    v = min(x for x in (m12, m12 + 720, m12 + 1440, m12 + 2160) if x >= prev)
                stops[name] = prev = v
            out[direction].append({"train": train, "stops": stops})
    return out


def trips(trains, origin, dest):
    rows = [(t["stops"][origin], t["stops"][dest], t["train"])
            for t in trains if origin in t["stops"] and dest in t["stops"]]
    return sorted(rows)


def hhmm(v):
    return f"{v // 60:02d}:{v % 60:02d}"


def render(data, today):
    def block(rows):
        return ",\n".join(f'      {{ train: "{n}", depart: "{hhmm(d)}", arrive: "{hhmm(a)}" }}'
                          for d, a, n in rows)
    body = ",\n".join(f"  {key}: {{\n    inbound: [\n{block(d['inbound'])}\n    ],\n"
                      f"    outbound: [\n{block(d['outbound'])}\n    ]\n  }}"
                      for key, d in data.items())
    return ("// GENERATED by scripts/update_schedules.py. Do not edit by hand.\n"
            f'window.SCHEDULE_INFO = {{ downloaded: "{today}" }};\n\n'
            "// Weekday trains, 24-hour times (values past 24:00 run after midnight).\n"
            "// inbound = home station -> downtown terminal; outbound = terminal -> home station.\n"
            "// Sources: https://schedules.metrarail.com/pdf/NCS.pdf, MD-N.pdf, UP-NW.pdf\n"
            f"window.SCHEDULES = {{\n{body}\n}};\n")


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--dry-run", action="store_true", help="print parsed trains without writing")
    ap.add_argument("--pdf-dir", help="use already-downloaded PDFs (NCS.pdf, MD-N.pdf, UP-NW.pdf) from this folder")
    args = ap.parse_args()

    data, problems = {}, []
    with tempfile.TemporaryDirectory() as tmp:
        for key, (pdf_name, home, terminal) in LINES.items():
            path = Path(args.pdf_dir) / f"{pdf_name}.pdf" if args.pdf_dir else download(pdf_name, tmp)
            parsed = parse_pdf(path)
            data[key] = {"inbound": trips(parsed["inbound"], home, terminal),
                         "outbound": trips(parsed["outbound"], terminal, home)}
            for direction, rows in data[key].items():
                print(f"{pdf_name:6} {direction:8} {len(rows):3} trains  "
                      + " ".join(f"{n}@{hhmm(d)}" for d, _, n in rows[:6]) + (" ..." if len(rows) > 6 else ""))
                if not rows:
                    stations = sorted({s for t in parsed[direction] for s in t["stops"]})
                    problems.append(f"{pdf_name} {direction}: no trains between {home!r} and {terminal!r}. "
                                    f"Stations found: {stations}")

    if problems:
        print("\nNot writing data/schedules.js. The PDF layout or station names may have changed:", file=sys.stderr)
        for p in problems:
            print("  - " + p, file=sys.stderr)
        sys.exit(1)

    if args.dry_run:
        print("\nDry run: data/schedules.js not changed.")
        return
    new = render(data, datetime.date.today().isoformat())
    old = OUT.read_text() if OUT.exists() else ""
    OUT.write_text(new)
    strip = lambda s: re.sub(r'downloaded: "[^"]*"', "", s)
    print(f"\nWrote {OUT.relative_to(OUT.parent.parent)}"
          + (" (no train changes)" if strip(old) == strip(new) else " (train times changed; review with git diff)"))


if __name__ == "__main__":
    main()
